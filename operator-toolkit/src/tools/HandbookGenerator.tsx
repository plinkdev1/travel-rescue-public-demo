import { useMemo, useState } from "react";
import { branding } from "../branding.config";

/** Turn a few operating parameters into a ready-to-use operator handbook (Markdown). */

type Params = {
  brand: string;
  support: string;
  settlement: "weekly" | "biweekly" | "monthly";
  paymentProvider: "Lemon Squeezy (MoR)" | "Stripe Connect" | "PayPal";
  regions: string;
  depositPolicy: string;
};

const DEFAULTS: Params = {
  brand: branding.productName,
  support: branding.supportEmail,
  settlement: "weekly",
  paymentProvider: "Lemon Squeezy (MoR)",
  regions: "Lisbon, London",
  depositPolicy: "Authorize on booking, release on inspected return, capture only on documented damage.",
};

function handbook(p: Params): string {
  return `# ${p.brand} — Operator Handbook

_Generated by the ${branding.productName} ${branding.toolkitName}. Edit freely; this is your starting runbook._

## 1. Daily
- **Reservations queue** — confirm new bookings are flowing; watch for stuck \`pending_payment\`.
- **Provider coverage** — every active region has online agents/spots/hosts; nudge low-coverage areas.
- **Moderation** — review flagged ratings in **Admin → Reviews**; hide abusive content (it disappears from customers instantly).
- **Support** — triage inbound at **${p.support}**; target first response < 4h.
- **Incidents** — check for failed payments / disputed reservations; see §6.

## 2. Weekly
- **Metrics review** — reservations, conversion, utilization, avg rental value, delivery share, NPS/ratings.
- **Payout sanity** — the multi-party ledger (handler/returner/delivery/pickup/storage/servicer/host) reconciles to rental volume.
- **Catalogue/markets** — add spots/hosts where demand outstrips supply (**Admin → Markets**, import via the toolkit's Data Importer).
- **Provider quality** — review low-rated providers; coach or pause.

## 3. Monthly — settlement (${p.settlement})
- Provider payouts run **${p.settlement}** via **${p.paymentProvider}** (regulated rails — the platform never custodies funds).
- Reconcile platform commission, subscriptions, sponsored revenue, refunds and captured deposits.
- Review fee config (**Admin → Fees & payouts**); adjust bps/flat rates as economics evolve.
- Pay brand revenue-share to sponsored partners (**Admin → Brand portal**).

## 4. Deposits & damage
- Policy: ${p.depositPolicy}
- Captures require evidence (photos + servicer inspection outcome). Disputed → \`disputed\` state until resolved.

## 5. Compliance & trust
- **Accounts** are admin-provisioned only — no self-signup. Keep RBAC least-privilege (owner/admin/merchant/providers).
- **Keys** live encrypted in **Admin → Integrations** — never in code or chat.
- **Privacy/GDPR** — location is sensitive personal data; honor data-subject requests; keep retention tight.
- **Single active payment provider** per tenant — never run two (prevents duplicate payouts).

## 6. Incident response
1. **Detect** — payment failure, outage, safety report, data concern.
2. **Contain** — pause the affected provider/region/reservation; switch comms to status updates.
3. **Communicate** — notify affected customers (in-app + email); set expectations.
4. **Resolve & record** — fix, refund/credit if warranted, log in the audit trail (**Admin → Audit log**).
5. **Review** — weekly post-incident note; adjust policy.

## 7. Regions in scope
${p.regions.split(",").map((r) => `- ${r.trim()}`).join("\n")}

---
_Support: ${p.support} · Settlement: ${p.settlement} · Provider: ${p.paymentProvider}_
`;
}

export default function HandbookGenerator() {
  const [p, setP] = useState<Params>(DEFAULTS);
  const md = useMemo(() => handbook(p), [p]);
  const set = <K extends keyof Params>(k: K, v: Params[K]) => setP((s) => ({ ...s, [k]: v }));

  const download = () => {
    const blob = new Blob([md], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `${p.brand.toLowerCase().replace(/\s+/g, "-")}-operator-handbook.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="grid gap-6 lg:grid-cols-2">
      <section className="rounded-tile border border-line bg-white p-5">
        <h2 className="text-base font-extrabold">Parameters</h2>
        <div className="mt-3 space-y-3">
          <Field label="Brand name" value={p.brand} onChange={(v) => set("brand", v)} />
          <Field label="Support contact" value={p.support} onChange={(v) => set("support", v)} />
          <Field label="Regions (comma-separated)" value={p.regions} onChange={(v) => set("regions", v)} />
          <label className="block text-xs font-semibold text-subtle">
            Settlement cadence
            <select value={p.settlement} onChange={(e) => set("settlement", e.target.value as Params["settlement"])} className="mt-1 w-full rounded-tile border border-line bg-canvas px-2 py-2 text-sm font-bold text-ink">
              <option value="weekly">weekly</option>
              <option value="biweekly">biweekly</option>
              <option value="monthly">monthly</option>
            </select>
          </label>
          <label className="block text-xs font-semibold text-subtle">
            Payment provider
            <select value={p.paymentProvider} onChange={(e) => set("paymentProvider", e.target.value as Params["paymentProvider"])} className="mt-1 w-full rounded-tile border border-line bg-canvas px-2 py-2 text-sm font-bold text-ink">
              <option>Lemon Squeezy (MoR)</option>
              <option>Stripe Connect</option>
              <option>PayPal</option>
            </select>
          </label>
          <label className="block text-xs font-semibold text-subtle">
            Deposit policy
            <textarea value={p.depositPolicy} onChange={(e) => set("depositPolicy", e.target.value)} className="mt-1 h-20 w-full rounded-tile border border-line bg-canvas p-2 text-sm text-ink outline-none focus:border-brand" />
          </label>
          <button onClick={download} className="rounded-pill bg-brand px-4 py-2 text-sm font-bold text-white">Download handbook (.md)</button>
        </div>
      </section>

      <section className="rounded-tile border border-line bg-white p-5">
        <h2 className="text-base font-extrabold">Preview</h2>
        <pre className="mt-3 h-[28rem] overflow-auto rounded-tile border border-line bg-canvas p-3 text-[11px] leading-snug whitespace-pre-wrap">{md}</pre>
      </section>
    </div>
  );
}

function Field({ label, value, onChange }: { label: string; value: string; onChange: (v: string) => void }) {
  return (
    <label className="block text-xs font-semibold text-subtle">
      {label}
      <input value={value} onChange={(e) => onChange(e.target.value)} className="mt-1 w-full rounded-tile border border-line bg-canvas px-2 py-2 text-sm font-bold text-ink outline-none focus:border-brand" />
    </label>
  );
}
